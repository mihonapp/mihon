package tachiyomi.data.manga

import eu.kanade.tachiyomi.source.model.UpdateStrategy
import kotlinx.serialization.json.JsonObject
import tachiyomi.domain.library.model.LibraryManga
import tachiyomi.domain.manga.model.Manga
import tachiyomi.domain.manga.model.MangaWithChapterCount

object MangaMapper {
    fun mapManga(
        id: Long,
        sourceId: Long,
        url: String,
        title: String,
        author: String?,
        artist: String?,
        description: String?,
        genre: List<String>?,
        status: Long,
        cover: String?,
        updateStrategy: UpdateStrategy,
        memo: JsonObject,
        favoriteAt: Long?,
        notes: String,
        readerFlags: Long,
        chapterFlags: Long,
        chapterLastUpdate: Long?,
        chapterNextUpdate: Long?,
        chapterFetchInterval: Long,
        coverLastModified: Long,
        initialized: Boolean,
        modifiedAt: Long,
    ): Manga = Manga(
        id = id,
        source = sourceId,
        favorite = favoriteAt != null,
        lastUpdate = chapterLastUpdate ?: 0,
        nextUpdate = chapterNextUpdate ?: 0,
        fetchInterval = chapterFetchInterval.toInt(),
        dateAdded = favoriteAt ?: 0,
        viewerFlags = readerFlags,
        chapterFlags = chapterFlags,
        coverLastModified = coverLastModified,
        url = url,
        title = title,
        artist = artist,
        author = author,
        description = description,
        genre = genre,
        status = status,
        thumbnailUrl = cover,
        updateStrategy = updateStrategy,
        initialized = initialized,
        lastModifiedAt = modifiedAt,
        favoriteModifiedAt = favoriteAt,
        version = 0,
        notes = notes,
        memo = memo,
    )

    fun mapLibraryManga(
        id: Long,
        sourceId: Long,
        url: String,
        title: String,
        author: String?,
        artist: String?,
        description: String?,
        genre: List<String>?,
        status: Long,
        cover: String?,
        updateStrategy: UpdateStrategy,
        memo: JsonObject,
        favoriteAt: Long,
        notes: String,
        readerFlags: Long,
        chapterFlags: Long,
        chapterLastUpdate: Long?,
        chapterNextUpdate: Long?,
        chapterFetchInterval: Long,
        coverLastModified: Long,
        initialized: Boolean,
        modifiedAt: Long,
        totalCount: Long,
        readCount: Double,
        latestUpload: Long,
        chapterFetchedAt: Long,
        lastRead: Long,
        bookmarkCount: Double,
        categories: String,
    ): LibraryManga = LibraryManga(
        manga = mapManga(
            id,
            sourceId,
            url,
            title,
            author,
            artist,
            description,
            genre,
            status,
            cover,
            updateStrategy,
            memo,
            favoriteAt,
            notes,
            readerFlags,
            chapterFlags,
            chapterLastUpdate,
            chapterNextUpdate,
            chapterFetchInterval,
            coverLastModified,
            initialized,
            modifiedAt,
        ),
        categories = categories.split(",").map { it.toLong() },
        totalChapters = totalCount,
        readCount = readCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        latestUpload = latestUpload,
        chapterFetchedAt = chapterFetchedAt,
        lastRead = lastRead,
    )

    fun mapMangaWithChapterCount(
        id: Long,
        sourceId: Long,
        url: String,
        title: String,
        author: String?,
        artist: String?,
        description: String?,
        genre: List<String>?,
        status: Long,
        cover: String?,
        updateStrategy: UpdateStrategy,
        memo: JsonObject,
        favoriteAt: Long?,
        notes: String,
        readerFlags: Long,
        chapterFlags: Long,
        chapterLastUpdate: Long?,
        chapterNextUpdate: Long?,
        chapterFetchInterval: Long,
        coverLastModified: Long,
        initialized: Boolean,
        modifiedAt: Long,
        totalCount: Long,
    ): MangaWithChapterCount = MangaWithChapterCount(
        manga = mapManga(
            id,
            sourceId,
            url,
            title,
            author,
            artist,
            description,
            genre,
            status,
            cover,
            updateStrategy,
            memo,
            favoriteAt,
            notes,
            readerFlags,
            chapterFlags,
            chapterLastUpdate,
            chapterNextUpdate,
            chapterFetchInterval,
            coverLastModified,
            initialized,
            modifiedAt,
        ),
        chapterCount = totalCount,
    )
}
