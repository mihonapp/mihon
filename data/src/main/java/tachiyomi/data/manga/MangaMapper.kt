package tachiyomi.data.manga

import eu.kanade.tachiyomi.source.model.UpdateStrategy
import kotlinx.serialization.json.JsonObject
import tachiyomi.domain.library.model.LibraryManga
import tachiyomi.domain.manga.model.Manga
import tachiyomi.domain.manga.model.MangaWithChapterCount

object MangaMapper {
    fun mapManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
    ): Manga = Manga(
        id = id,
        source = sourceId,
        favoriteAt = userFavoriteAt,
        lastUpdate = stateChapterLastUpdate ?: 0,
        nextUpdate = stateChapterNextUpdate ?: 0,
        fetchInterval = stateChapterFetchInterval.toInt(),
        viewerFlags = userReaderFlags,
        chapterFlags = userChapterFlags,
        coverLastModified = stateCoverLastModified,
        url = remoteUrl,
        title = remoteTitle,
        artist = remoteArtist,
        author = remoteAuthor,
        description = remoteDescription,
        genre = remoteGenre,
        status = remoteStatus,
        thumbnailUrl = remoteCover,
        updateStrategy = remoteUpdateStrategy,
        initialized = stateInitialized,
        notes = userNotes,
        memo = remoteMemo,
    )

    fun mapLibraryManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
        totalCount: Long,
        readCount: Double,
        latestUpload: Long,
        chapterFetchedAt: Long,
        lastRead: Long,
        bookmarkCount: Double,
        categories: String,
    ): LibraryManga = LibraryManga(
        manga = mapManga(
            id = id,
            sourceId = sourceId,
            remoteUrl = remoteUrl,
            remoteTitle = remoteTitle,
            remoteAuthor = remoteAuthor,
            remoteArtist = remoteArtist,
            remoteDescription = remoteDescription,
            remoteGenre = remoteGenre,
            remoteStatus = remoteStatus,
            remoteCover = remoteCover,
            remoteUpdateStrategy = remoteUpdateStrategy,
            remoteMemo = remoteMemo,
            userFavoriteAt = userFavoriteAt,
            userNotes = userNotes,
            userReaderFlags = userReaderFlags,
            userChapterFlags = userChapterFlags,
            stateChapterLastUpdate = stateChapterLastUpdate,
            stateChapterNextUpdate = stateChapterNextUpdate,
            stateChapterFetchInterval = stateChapterFetchInterval,
            stateCoverLastModified = stateCoverLastModified,
            stateInitialized = stateInitialized,
        ),
        categories = categories.split(",").map { it.toLong() },
        totalChapters = totalCount,
        readCount = readCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        latestUpload = latestUpload,
        chapterFetchedAt = chapterFetchedAt,
        lastRead = lastRead,
    )

    fun mapMangaWithChapterCount(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
        chapterCount: Long,
    ): MangaWithChapterCount = MangaWithChapterCount(
        manga = mapManga(
            id = id,
            sourceId = sourceId,
            remoteUrl = remoteUrl,
            remoteTitle = remoteTitle,
            remoteAuthor = remoteAuthor,
            remoteArtist = remoteArtist,
            remoteDescription = remoteDescription,
            remoteGenre = remoteGenre,
            remoteStatus = remoteStatus,
            remoteCover = remoteCover,
            remoteUpdateStrategy = remoteUpdateStrategy,
            remoteMemo = remoteMemo,
            userFavoriteAt = userFavoriteAt,
            userNotes = userNotes,
            userReaderFlags = userReaderFlags,
            userChapterFlags = userChapterFlags,
            stateChapterLastUpdate = stateChapterLastUpdate,
            stateChapterNextUpdate = stateChapterNextUpdate,
            stateChapterFetchInterval = stateChapterFetchInterval,
            stateCoverLastModified = stateCoverLastModified,
            stateInitialized = stateInitialized,
        ),
        chapterCount = chapterCount,
    )
}
